#!/usr/bin/env python3
"""Generate and replay named Lean declarations in research paper axiom reports.

The reports are the pinned expected result. The generated ``Census.lean``
imports the package's declared Lake roots and issues one ``#print axioms``
command for every reported declaration. Replay compares declaration names
and normalized axiom sets; it does not infer broader source coverage.
"""

from __future__ import annotations

import argparse
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

DEPENDENCY_LINE = re.compile(r"^'(.+)' depends on axioms: \[(.*)\]$")
NO_DEPENDENCY_LINE = re.compile(r"^'(.+)' does not depend on any axioms$")
HEADER_NUMBER = re.compile(
    r"^(Declarations listed|Declarations with no axioms|"
    r"Declarations with axiom dependencies): (\d+)$"
)
LAKE_ROOTS = re.compile(r"roots\s*:=\s*#\[(.*?)\]", re.DOTALL)
AXIOM_WHITELIST = frozenset({"Quot.sound", "propext", "Classical.choice", "choice"})


@dataclass(frozen=True)
class Declaration:
    name: str
    axioms: frozenset[str]


def _declarations(text: str, source: Path | str) -> list[Declaration]:
    declarations: list[Declaration] = []
    for line in text.splitlines():
        no_dependency = NO_DEPENDENCY_LINE.fullmatch(line)
        dependency = DEPENDENCY_LINE.fullmatch(line)
        if no_dependency is not None:
            declarations.append(Declaration(no_dependency.group(1), frozenset()))
        elif dependency is not None:
            axioms = frozenset(
                axiom.strip() for axiom in dependency.group(2).split(",") if axiom.strip()
            )
            if not axioms:
                raise ValueError(f"empty axiom list in {source}: {line}")
            declarations.append(Declaration(dependency.group(1), axioms))
    names = [declaration.name for declaration in declarations]
    if len(names) != len(set(names)):
        raise ValueError(f"duplicate declaration in {source}")
    return declarations


def parse_report(paper_dir: Path) -> list[Declaration]:
    report = paper_dir / "lean4" / "axiom_report.txt"
    if not report.is_file():
        raise FileNotFoundError(f"axiom_report.txt not found at {report}")
    text = report.read_text(encoding="utf-8")
    declarations = _declarations(text, report)
    header_matches = [
        match
        for line in text.splitlines()
        if (match := HEADER_NUMBER.fullmatch(line)) is not None
    ]
    headers = {match.group(1): int(match.group(2)) for match in header_matches}
    required = {
        "Declarations listed",
        "Declarations with no axioms",
        "Declarations with axiom dependencies",
    }
    if len(header_matches) == len(required) and headers.keys() == required:
        without_axioms = sum(not declaration.axioms for declaration in declarations)
        with_axioms = len(declarations) - without_axioms
        actual_counts = (len(declarations), without_axioms, with_axioms)
        reported_counts = (
            headers["Declarations listed"],
            headers["Declarations with no axioms"],
            headers["Declarations with axiom dependencies"],
        )
        if actual_counts != reported_counts:
            raise ValueError(
                f"report counts disagree in {report}: {reported_counts} != {actual_counts}"
            )
    return declarations


def import_roots(paper_dir: Path) -> list[str]:
    lean_root = paper_dir / "lean4"
    lakefile = lean_root / "lakefile.lean"
    if not lakefile.is_file():
        return ["Core"]
    text = lakefile.read_text(encoding="utf-8")
    match = LAKE_ROOTS.search(text)
    if match is not None:
        roots = re.findall(r"`([A-Za-z0-9_.]+)", match.group(1))
        if roots:
            return roots
    lean_files = sorted(f.stem for f in lean_root.glob("*.lean") if f.name not in ("Census.lean", "lakefile.lean"))
    return lean_files or ["Core"]


def render_census(paper_dir: Path) -> str:
    declarations = parse_report(paper_dir)
    lines = [
        "/-",
        "Deterministic census generated by replay_lean_axiom_census.py.",
        "Replays declarations named in lean4/axiom_report.txt.",
        "Standalone build: lake build",
        "Standalone replay: lake env lean Census.lean",
        "-/",
    ]
    for root in import_roots(paper_dir):
        lines.append(f"import {root}")
    lines.append("")
    for dec in declarations:
        lines.append(f"#print axioms {dec.name}")
    return "\n".join(lines) + "\n"


def census_path(paper_dir: Path) -> Path:
    return paper_dir / "lean4" / "Census.lean"


def write_census(paper_dir: Path) -> None:
    path = census_path(paper_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_census(paper_dir))


def check_census(paper_dir: Path) -> None:
    path = census_path(paper_dir)
    if not path.is_file():
        raise FileNotFoundError(f"Census.lean missing at {path}")
    actual = path.read_text(encoding="utf-8")
    expected = render_census(paper_dir)
    if actual != expected:
        raise ValueError(f"stale generated census: {path}")


def replay_census(paper_dir: Path, timeout_seconds: int = 120) -> None:
    check_census(paper_dir)
    lean_root = paper_dir / "lean4"
    build = subprocess.run(
        ["lake", "build"],
        cwd=lean_root,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=timeout_seconds,
    )
    if build.returncode != 0:
        raise ValueError(f"Lake build failed with exit {build.returncode}:\n{build.stdout}\n{build.stderr}")
    completed = subprocess.run(
        ["lake", "env", "lean", "Census.lean"],
        cwd=lean_root,
        capture_output=True,
        text=True,
        encoding="utf-8",
        timeout=timeout_seconds,
    )
    if completed.returncode != 0:
        raise ValueError(f"Lean replay failed with exit {completed.returncode}:\n{completed.stdout}\n{completed.stderr}")
    expected = parse_report(paper_dir)
    actual = _declarations(completed.stdout, f"Lean replay for {paper_dir.name}")
    if actual != expected:
        raise ValueError(f"Lean replay declaration mismatch for {paper_dir.name}")


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate Census.lean")
    mode.add_argument("--replay", action="store_true", help="run Lean and compare output")
    mode.add_argument("--check", action="store_true", help="check generated files (default)")
    parser.add_argument("--timeout-seconds", type=int, default=120)
    parser.add_argument("package_path", nargs="?", default=".", help="Paper directory path")
    args = parser.parse_args()

    paper_dir = Path(args.package_path).resolve()
    try:
        if args.write:
            write_census(paper_dir)
            print(f"OK {paper_dir.name}: generated Census.lean")
        elif args.replay:
            replay_census(paper_dir, args.timeout_seconds)
            print(f"OK {paper_dir.name}: replayed census successfully")
        else:
            check_census(paper_dir)
            print(f"OK {paper_dir.name}: Census.lean is up to date")
    except Exception as error:
        print(f"FAIL {paper_dir.name}: {error}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
