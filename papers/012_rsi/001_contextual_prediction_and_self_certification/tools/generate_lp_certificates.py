"""Generate exact solver fixtures and Lean-checkable rational certificates.

--check recomputes the certificates and refuses any source/data drift. The
generated Lean facts check the numbers rather than trusting this generator.
"""
from dataclasses import asdict
from fractions import Fraction as Q
import argparse
import hashlib
from itertools import product
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'code'))
import contextuality_lp as lp
import epistemic_kernel as k


def bell(table):
    return lp.Scenario((2, 2, 2, 2), ((0, 2), (0, 3), (1, 2), (1, 3)),
                       tuple(tuple(table[c].get(o, Q(0)) for o in product((0, 1), repeat=2))
                             for c in k.CONTEXTS))


def fixtures():
    s = Q(1, 2) + Q(1, 100000000)
    boundary = {c: {o: (1 + (s if (o[0] ^ o[1]) == (c[0] & c[1]) else -s)) / 4
                    for o in product((0, 1), repeat=2)} for c in k.CONTEXTS}
    return {'classical': bell(k.classical_mixture()), 'pr': bell(k.pr_box()),
            'near': bell(k.near_tsirelson()), 'boundary': bell(boundary),
            'triangle': lp.Scenario((2, 2, 2), ((0, 1), (0, 2), (1, 2)),
                ((Q(0), Q(1, 2), Q(1, 2), Q(0)),) * 3)}


def lean_q(q):
    return f'({q.numerator} / {q.denominator})' if q.denominator != 1 else str(q.numerator)


def vector(values):
    return '![' + ', '.join(lean_q(q) for q in values) + ']'


def generate():
    cases = {}
    lines = ['-- Generated by tools/generate_lp_certificates.py; exact numbers checked below.',
             'import ContextualDuality', '', 'set_option maxRecDepth 10000',
             'set_option maxHeartbeats 4000000', 'open scoped BigOperators',
             'open EpistemicNoGo.ContextualDuality',
             'namespace EpistemicNoGo.RationalCertificates', '']
    for name, model in fixtures().items():
        result = lp.evaluate(model)
        cert = result.certificate
        _, columns, target = lp.contextual_matrix(model)
        ng, ni = len(columns), len(target)
        cases[name] = {'model': asdict(model), 'kind': result.kind,
                       'generators': columns, 'target': target, 'certificate': asdict(cert)}
        lines.extend([f'def {name}A : Fin {ng} → Fin {ni} → ℚ := ![' + ',\n  '.join(vector(c) for c in columns) + ']',
            f'def {name}E : Fin {ni} → ℚ := {vector(target)}',
            f'def {name}P : Fin {ng} → ℚ := {vector(cert.coefficients)}',
            f'def {name}Y : Fin {ni} → ℚ := {vector(cert.witness)}',
            f'def {name}Z : ℚ := {lean_q(cert.offset)}',
            f'def {name}D : ℚ := {lean_q(cert.defect)}', '',
            f'theorem {name}_certificate :',
            f'    (∀ g, 0 ≤ {name}P g) ∧ (∑ g, {name}P g = 1) ∧',
            f'    (∀ i, |{name}Y i| ≤ 1) ∧ (∀ g, pairing {name}Y ({name}A g) + {name}Z ≤ 0) ∧',
            f'    pairing {name}Y {name}E + {name}Z = cost {name}A {name}E {name}P ∧',
            f'    cost {name}A {name}E {name}P = {name}D := by',
            f'  norm_num [pairing, mix, cost, {name}A, {name}E, {name}P, {name}Y, {name}Z, {name}D,',
            '    Fin.sum_univ_succ, Fin.forall_fin_succ]', '',
            f'theorem {name}_optimal_over_reals :',
            f'    ∀ q : Fin {ng} → ℝ, (∀ g, 0 ≤ q g) → (∑ g, q g = 1) →',
            f'      ({name}D : ℝ) ≤ cost (fun g i => ({name}A g i : ℝ)) (fun i => ({name}E i : ℝ)) q := by',
            f'  rcases {name}_certificate with ⟨_, _, hy, hz, hgap, hvalue⟩',
            '  intro q hq hs',
            f'  have hh := rational_certificate_real_optimal {name}A {name}E {name}Y {name}P {name}Z hy hz hgap q hq hs',
            '  simpa only [hvalue] using hh', ''])
    lines.append('end EpistemicNoGo.RationalCertificates')
    source_sha = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
                  for name in ['code/contextuality_lp.py', 'code/epistemic_kernel.py', 'tools/generate_lp_certificates.py']}
    record = {'schema': 'contextuality.exact-lp-fixtures.v1', 'source_sha256': source_sha,
              'scope': 'Exact rational feasible primal/dual pairs. Pivot counts are diagnostic, not certificate premises.',
              'cases': cases}
    encode = lambda v: f'{v.numerator}/{v.denominator}' if type(v) is Q else v
    return {'docs/lp_certificates.json': json.dumps(record, indent=2, default=encode) + '\n',
            'lean4/RationalCertificates.lean': '\n'.join(lines) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generate().items():
        target = ROOT / name
        if args.check:
            if target.read_text(encoding='utf-8') != text:
                raise SystemExit(f'FAIL: generated certificate drift: {name}')
        else:
            target.write_text(text, encoding='utf-8')
    print('PASS: five exact solver fixtures and their Lean certificate source agree')
