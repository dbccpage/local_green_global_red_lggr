from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from typing import Callable, Dict, List, Optional, Tuple, Union


@dataclass(frozen=True)
class Edge:
    """Directed edge between two vertices."""
    source: int
    target: int


@dataclass(frozen=True)
class FiniteGraph:
    """Finite connected directed graph P = (V, E)."""
    vertices: Tuple[int, ...]
    edges: Tuple[Edge, ...]

    def edge_index(self, edge: Edge) -> int:
        return self.edges.index(edge)

    @property
    def num_vertices(self) -> int:
        return len(self.vertices)

    @property
    def num_edges(self) -> int:
        return len(self.edges)


@dataclass(frozen=True)
class AdmittedComplex:
    """
    Admitted finite 2-complex with verified coboundary condition d_1 o d_0 = 0.
    d_0 is the vertex-to-edge incidence matrix (coboundary d_0 f(e_ij) = f(j) - f(i)).
    d_1 is the 2-cell boundary matrix mapping edge 1-cochains to 2-cells.
    """
    graph: FiniteGraph
    d1_matrix: Optional[Tuple[Tuple[int, ...], ...]] = None

    def __post_init__(self) -> None:
        if self.d1_matrix is not None:
            num_edges = len(self.graph.edges)
            for row_idx, row in enumerate(self.d1_matrix):
                if len(row) != num_edges:
                    raise ValueError(
                        f"Row {row_idx} width ({len(row)}) does not match graph edge dimension ({num_edges})"
                    )
                # Verify d_1 o d_0 = 0 on every vertex
                for v in self.graph.vertices:
                    comp = 0
                    for e_idx, coeff in enumerate(row):
                        edge = self.graph.edges[e_idx]
                        if v == edge.target:
                            comp += coeff
                        if v == edge.source:
                            comp -= coeff
                    if comp != 0:
                        raise ValueError(
                            f"Complex validation failed: d_1 o d_0 != 0 on face {row_idx}, vertex {v} (residual={comp})"
                        )


@dataclass(frozen=True)
class ExactPrimalDualWitness:
    """
    Exact rational witness for L1 coboundary obstruction Phi_1:
    - potential: 0-cochain potential f in Q^V (fixing gauge).
    - dual_flow: 1-cycle flow z in Q^E satisfying B^T z = 0 and ||z||_infinity <= 1.
    Certified when primal residual r = omega - d0(f) satisfies ||r||_1 == <z, omega>.
    """
    potential: Tuple[Fraction, ...]
    dual_flow: Tuple[Fraction, ...]


@dataclass(frozen=True)
class OperatorProposal:
    """Candidate field evolution generated by an operator on an admitted carrier."""
    operator_id: str
    parameters: Dict[str, str]
    initial_field: Tuple[Fraction, ...]
    proposed_field: Tuple[Fraction, ...]


@dataclass(frozen=True)
class StructuralOperatorProposal:
    """Candidate field evolution generated by a structural operator between distinct carriers."""
    operator_id: str
    parameters: Dict[str, str]
    source_carrier: AdmittedComplex
    target_carrier: AdmittedComplex
    initial_field: Tuple[Fraction, ...]
    proposed_field: Tuple[Fraction, ...]
    carrier_map: Dict[int, int]


@dataclass(frozen=True)
class EvaluatorPolicy:
    """Policy thresholds and tolerances for the guarded evaluator."""
    max_r_cl: Fraction
    max_phi1: Optional[Fraction] = None
    max_gamma2: Optional[Fraction] = None
    epsilon_guard: Fraction = Fraction(1, 1000)

    def __post_init__(self) -> None:
        if self.max_r_cl < Fraction(0, 1):
            raise ValueError(f"Domain error: max_r_cl ({self.max_r_cl}) must be non-negative.")
        if self.epsilon_guard <= Fraction(0, 1):
            raise ValueError(f"Domain error: epsilon_guard ({self.epsilon_guard}) must be strictly positive.")
        if self.max_phi1 is not None and self.max_phi1 < Fraction(0, 1):
            raise ValueError(f"Domain error: max_phi1 ({self.max_phi1}) must be non-negative.")
        if self.max_gamma2 is not None and self.max_gamma2 < Fraction(0, 1):
            raise ValueError(f"Domain error: max_gamma2 ({self.max_gamma2}) must be non-negative.")


@dataclass(frozen=True)
class ObstructionTuple:
    """
    Evaluator diagnostic tuple (Phi_1, Gamma_2, R_cl, Xi).
    R_cl is None when +infinity (unbounded curvature: Gamma_2 > epsilon while Phi_1 <= epsilon).
    Also records exact algebraic ratio R_exact and named routing status.
    """
    phi1: Fraction
    gamma2: Fraction
    r_cl: Optional[Fraction]
    xi: Fraction = Fraction(0, 1)
    r_exact: Optional[Fraction] = None
    routing_status: str = "REGULAR"

    def __post_init__(self) -> None:
        if self.phi1 < Fraction(0, 1):
            raise ValueError(f"Domain error: Phi_1 ({self.phi1}) must be non-negative.")
        if self.gamma2 < Fraction(0, 1):
            raise ValueError(f"Domain error: Gamma_2 ({self.gamma2}) must be non-negative.")
        if self.xi < Fraction(0, 1):
            raise ValueError(f"Domain error: Xi ({self.xi}) must be non-negative.")
        if self.r_cl is not None and self.r_cl < Fraction(0, 1):
            raise ValueError(f"Domain error: R_cl ({self.r_cl}) must be non-negative.")


def discrete_coboundary(graph: FiniteGraph, potential: Dict[int, Fraction]) -> List[Fraction]:
    """Compute discrete coboundary d_0 f on edge e_ij = f(j) - f(i)."""
    result = []
    for edge in graph.edges:
        f_j = potential.get(edge.target, Fraction(0, 1))
        f_i = potential.get(edge.source, Fraction(0, 1))
        result.append(f_j - f_i)
    return result


def compute_cycle_defect(cycle_edges: List[Tuple[Edge, int]], edge_field: Dict[Edge, Fraction]) -> Fraction:
    """Compute cycle defect Delta(C) = sum_{e in C} epsilon_e * omega(e), epsilon_e in {-1, 1}."""
    total = Fraction(0, 1)
    for edge, sign in cycle_edges:
        val = edge_field.get(edge, Fraction(0, 1))
        total += val if sign > 0 else -val
    return total


def compute_phi1_cycle_graph(cycle_field: Union[List[Fraction], Tuple[Fraction, ...]]) -> Fraction:
    """
    Specialized helper for a single directed cycle C_n:
    The L1 obstruction Phi_1 is exactly inf_{f} sum_i |omega_i - (f_{i+1} - f_i)| = |sum_i omega_i|.
    This formula is valid specifically for coherently oriented single cycles.
    """
    return abs(sum(cycle_field, Fraction(0, 1)))


def verify_primal_dual_witness(
    graph: FiniteGraph,
    field: Tuple[Fraction, ...],
    witness: ExactPrimalDualWitness,
) -> Fraction:
    """
    Verify an exact primal/dual witness for Phi_1(field) on graph:
    1. Residual r = omega - B f
    2. Dual feasibility: B^T z = 0 at every vertex (divergence-free flow)
    3. Dual norm bound: ||z||_infinity <= 1
    4. Complementary slackness: ||r||_1 == <z, omega>.
    Returns certified Phi_1 = ||r||_1.
    Raises ValueError on invalid dimensions, infeasibility, or non-zero duality gap.
    """
    v_count = len(graph.vertices)
    e_count = len(graph.edges)
    if len(field) != e_count:
        raise ValueError(f"Field dimension ({len(field)}) does not match graph edge count ({e_count})")
    if len(witness.potential) != v_count:
        raise ValueError(f"Witness potential dimension ({len(witness.potential)}) does not match vertex count ({v_count})")
    if len(witness.dual_flow) != e_count:
        raise ValueError(f"Witness dual flow dimension ({len(witness.dual_flow)}) does not match edge count ({e_count})")

    v_index = {v: idx for idx, v in enumerate(graph.vertices)}
    f = witness.potential
    z = witness.dual_flow

    primal_val = Fraction(0, 1)
    for e_idx, edge in enumerate(graph.edges):
        u_idx = v_index[edge.source]
        v_idx = v_index[edge.target]
        coboundary_e = f[v_idx] - f[u_idx]
        r_e = field[e_idx] - coboundary_e
        primal_val += abs(r_e)

    div = [Fraction(0, 1) for _ in graph.vertices]
    for e_idx, edge in enumerate(graph.edges):
        u_idx = v_index[edge.source]
        v_idx = v_index[edge.target]
        div[v_idx] += z[e_idx]
        div[u_idx] -= z[e_idx]

    for v_idx, d in enumerate(div):
        if d != Fraction(0, 1):
            raise ValueError(f"Dual flow infeasible: non-zero divergence ({d}) at vertex {graph.vertices[v_idx]}")

    for e_idx, z_e in enumerate(z):
        if abs(z_e) > Fraction(1, 1):
            raise ValueError(f"Dual flow infeasible: ||z||_infinity violated at edge {e_idx} (|{z_e}| > 1)")

    dual_val = Fraction(0, 1)
    for e_idx, z_e in enumerate(z):
        dual_val += z_e * field[e_idx]

    if primal_val != dual_val:
        raise ValueError(f"Duality gap detected: primal ||r||_1 ({primal_val}) != dual <z, omega> ({dual_val})")

    return primal_val


def solve_tree_witness(graph: FiniteGraph, field: Tuple[Fraction, ...]) -> ExactPrimalDualWitness:
    """
    Construct exact primal/dual witness for tree graphs (Tree Exactness):
    Every tree has H^1 = 0, so Phi_1 = 0 with residual r = 0 and dual z = 0.
    """
    V = len(graph.vertices)
    v_index = {v: i for i, v in enumerate(graph.vertices)}
    adj: Dict[int, List[Tuple[int, int, Fraction]]] = {i: [] for i in range(V)}
    for e_idx, edge in enumerate(graph.edges):
        u = v_index[edge.source]
        v = v_index[edge.target]
        adj[u].append((v, e_idx, Fraction(1, 1)))
        adj[v].append((u, e_idx, Fraction(-1, 1)))

    pot = [None] * V
    pot[0] = Fraction(0, 1)
    queue = [0]
    while queue:
        curr = queue.pop(0)
        curr_pot = pot[curr]
        assert curr_pot is not None
        for nxt, e_idx, sign in adj[curr]:
            if pot[nxt] is None:
                pot[nxt] = curr_pot + sign * field[e_idx]
                queue.append(nxt)

    if any(p is None for p in pot):
        raise ValueError("Disconnected graph cannot be certified as a single tree")

    potential_tuple = tuple(p for p in pot if p is not None)
    dual_flow = tuple(Fraction(0, 1) for _ in graph.edges)
    witness = ExactPrimalDualWitness(potential=potential_tuple, dual_flow=dual_flow)
    verify_primal_dual_witness(graph, field, witness)
    return witness


def solve_directed_cycle_witness(graph: FiniteGraph, field: Tuple[Fraction, ...]) -> ExactPrimalDualWitness:
    """
    Construct exact primal/dual witness for a single directed cycle C_n.
    Dual flow z = s * (1, ..., 1) where s = sgn(sum omega).
    Primal potential puts the net holonomy on the closing edge, verifying zero duality gap.
    """
    V = len(graph.vertices)
    E = len(graph.edges)
    if V != E:
        raise ValueError(f"Graph is not a single simple cycle: |V|={V} != |E|={E}")

    holonomy = sum(field, Fraction(0, 1))
    s = Fraction(1, 1) if holonomy >= Fraction(0, 1) else Fraction(-1, 1)
    z = tuple(s for _ in range(E))

    v_index = {v: i for i, v in enumerate(graph.vertices)}
    pot = [Fraction(0, 1)] * V
    for e_idx in range(E - 1):
        edge = graph.edges[e_idx]
        u = v_index[edge.source]
        v = v_index[edge.target]
        pot[v] = pot[u] + field[e_idx]

    witness = ExactPrimalDualWitness(potential=tuple(pot), dual_flow=z)
    verify_primal_dual_witness(graph, field, witness)
    return witness


def solve_lp_exact(c: List[Fraction], A: List[List[Fraction]], b: List[Fraction]) -> Tuple[Fraction, List[Fraction]]:
    """
    Solve min c^T x subject to A x = b, x >= 0 using two-phase simplex over exact fractions.
    """
    m = len(A)
    n = len(c)
    A_work = [[Fraction(val) for val in row] for row in A]
    b_work = [Fraction(val) for val in b]
    c_work = [Fraction(val) for val in c]
    for i in range(m):
        if b_work[i] < 0:
            b_work[i] = -b_work[i]
            for j in range(n):
                A_work[i][j] = -A_work[i][j]

    tableau: List[List[Fraction]] = []
    for i in range(m):
        row = list(A_work[i]) + [Fraction(0)] * m + [b_work[i]]
        row[n + i] = Fraction(1)
        tableau.append(row)

    phase1_obj = [Fraction(0)] * (n + m + 1)
    for j in range(n):
        s_val = sum(tableau[i][j] for i in range(m))
        phase1_obj[j] = -s_val
    phase1_obj[-1] = -sum(b_work)
    tableau.append(phase1_obj)
    basis = [n + i for i in range(m)]

    def pivot(p_row: int, p_col: int) -> None:
        pivot_val = tableau[p_row][p_col]
        for j in range(len(tableau[0])):
            tableau[p_row][j] /= pivot_val
        for i in range(len(tableau)):
            if i != p_row:
                factor = tableau[i][p_col]
                if factor != 0:
                    for j in range(len(tableau[0])):
                        tableau[i][j] -= factor * tableau[p_row][j]
        basis[p_row] = p_col

    # Phase 1
    while True:
        min_val = Fraction(0)
        p_col = -1
        for j in range(n + m):
            if tableau[-1][j] < min_val:
                min_val = tableau[-1][j]
                p_col = j
        if p_col == -1:
            break
        min_ratio = None
        p_row = -1
        for i in range(m):
            if tableau[i][p_col] > 0:
                ratio = tableau[i][-1] / tableau[i][p_col]
                if min_ratio is None or ratio < min_ratio:
                    min_ratio = ratio
                    p_row = i
        if p_row == -1:
            raise ValueError("Phase 1 unbounded in exact solver")
        pivot(p_row, p_col)

    if tableau[-1][-1] != 0:
        raise ValueError("Infeasible LP in exact solver")

    # Phase 2
    phase2_tableau: List[List[Fraction]] = []
    for i in range(m):
        phase2_tableau.append(tableau[i][:n] + [tableau[i][-1]])

    phase2_obj = list(c_work) + [Fraction(0)]
    for i in range(m):
        b_var = basis[i]
        if b_var < n:
            factor = phase2_obj[b_var]
            for j in range(n + 1):
                phase2_obj[j] -= factor * phase2_tableau[i][j]
    phase2_tableau.append(phase2_obj)
    tableau = phase2_tableau

    while True:
        min_val = Fraction(0)
        p_col = -1
        for j in range(n):
            if tableau[-1][j] < min_val:
                min_val = tableau[-1][j]
                p_col = j
        if p_col == -1:
            break
        min_ratio = None
        p_row = -1
        for i in range(m):
            if tableau[i][p_col] > 0:
                ratio = tableau[i][-1] / tableau[i][p_col]
                if min_ratio is None or ratio < min_ratio:
                    min_ratio = ratio
                    p_row = i
        if p_row == -1:
            raise ValueError("Phase 2 unbounded in exact solver")
        pivot(p_row, p_col)

    opt_val = -tableau[-1][-1]
    x = [Fraction(0)] * n
    for i in range(m):
        if basis[i] < n:
            x[basis[i]] = tableau[i][-1]
    return opt_val, x


def solve_graph_l1_exact(graph: FiniteGraph, field: Tuple[Fraction, ...]) -> Tuple[Fraction, ExactPrimalDualWitness]:
    """
    Exact rational linear program solver for L1 coboundary obstruction on arbitrary finite graphs.
    Solves primal and dual exactly, verifying zero duality gap via verify_primal_dual_witness.
    """
    V = len(graph.vertices)
    E = len(graph.edges)
    v_idx = {v: i for i, v in enumerate(graph.vertices)}

    # Check tree exactness fast path
    if E == V - 1:
        try:
            w = solve_tree_witness(graph, field)
            return Fraction(0, 1), w
        except ValueError:
            pass

    # Check simple directed cycle fast path
    if E == V:
        try:
            w = solve_directed_cycle_witness(graph, field)
            phi = abs(sum(field, Fraction(0, 1)))
            return phi, w
        except ValueError:
            pass

    # Dual formulation: max sum omega_e z_e s.t. B^T z = 0, -1 <= z_e <= 1
    # Standard form: min - sum omega_e (y_e - 1)
    # y_e in [0, 2], s_e in [0, 2], y_e + s_e = 2
    b_target = [Fraction(0)] * V
    for e_idx, edge in enumerate(graph.edges):
        b_target[v_idx[edge.target]] += Fraction(1)
        b_target[v_idx[edge.source]] -= Fraction(1)

    A: List[List[Fraction]] = []
    b: List[Fraction] = []
    for v in range(V - 1):
        row = [Fraction(0)] * (2 * E)
        for e_idx, edge in enumerate(graph.edges):
            if v_idx[edge.target] == v:
                row[e_idx] += Fraction(1)
            if v_idx[edge.source] == v:
                row[e_idx] -= Fraction(1)
        A.append(row)
        b.append(b_target[v])

    for e_idx in range(E):
        row = [Fraction(0)] * (2 * E)
        row[e_idx] = Fraction(1)
        row[E + e_idx] = Fraction(1)
        A.append(row)
        b.append(Fraction(2))

    c = [-field[e] for e in range(E)] + [Fraction(0)] * E
    _, sol = solve_lp_exact(c, A, b)
    z = tuple(sol[e] - Fraction(1) for e in range(E))

    # Primal formulation to obtain potential f
    num_p_vars = E + 2 * (V - 1) + 2 * E
    A_p: List[List[Fraction]] = []
    b_p: List[Fraction] = []
    for e_idx, edge in enumerate(graph.edges):
        u_src = v_idx[edge.source]
        u_tgt = v_idx[edge.target]
        row1 = [Fraction(0)] * num_p_vars
        row1[e_idx] = Fraction(1)
        if u_tgt > 0:
            row1[E + (u_tgt - 1)] -= Fraction(1)
            row1[E + (V - 1) + (u_tgt - 1)] += Fraction(1)
        if u_src > 0:
            row1[E + (u_src - 1)] += Fraction(1)
            row1[E + (V - 1) + (u_src - 1)] -= Fraction(1)
        row1[E + 2 * (V - 1) + 2 * e_idx] = Fraction(-1)
        A_p.append(row1)
        b_p.append(-field[e_idx])

        row2 = [Fraction(0)] * num_p_vars
        row2[e_idx] = Fraction(1)
        if u_tgt > 0:
            row2[E + (u_tgt - 1)] += Fraction(1)
            row2[E + (V - 1) + (u_tgt - 1)] -= Fraction(1)
        if u_src > 0:
            row2[E + (u_src - 1)] -= Fraction(1)
            row2[E + (V - 1) + (u_src - 1)] += Fraction(1)
        row2[E + 2 * (V - 1) + 2 * e_idx + 1] = Fraction(-1)
        A_p.append(row2)
        b_p.append(field[e_idx])

    c_p = [Fraction(1)] * E + [Fraction(0)] * (2 * (V - 1) + 2 * E)
    _, p_sol = solve_lp_exact(c_p, A_p, b_p)
    f_list = [Fraction(0)] * V
    for v in range(1, V):
        f_list[v] = p_sol[E + (v - 1)] - p_sol[E + (V - 1) + (v - 1)]
    potential = tuple(f_list)

    witness = ExactPrimalDualWitness(potential=potential, dual_flow=z)
    certified_phi = verify_primal_dual_witness(graph, field, witness)
    return certified_phi, witness


def compute_gamma2_simple(
    d1_matrix: Union[List[List[int]], Tuple[Tuple[int, ...], ...]],
    field_or_residual: Union[List[Fraction], Tuple[Fraction, ...]],
) -> Fraction:
    """
    Compute closure defect Gamma_2 = ||d_1 h_1||_1 for a declared 2-cell boundary matrix d_1.
    Because d_1 o d_0 = 0 on any declared 2-complex, d_1 h_1 = d_1 (omega - d_0 f*) = d_1 omega.
    Rejects malformed matrix rows whose width differs from the field dimension.
    """
    total = Fraction(0, 1)
    field_len = len(field_or_residual)
    for row_idx, row in enumerate(d1_matrix):
        if len(row) != field_len:
            raise ValueError(
                f"Row {row_idx} width ({len(row)}) does not match field dimension ({field_len})"
            )
        cell_sum = Fraction(0, 1)
        for coeff, val in zip(row, field_or_residual):
            cell_sum += Fraction(coeff, 1) * val
        total += abs(cell_sum)
    return total


def compute_r_exact(
    phi1: Fraction,
    gamma2: Fraction,
) -> Optional[Fraction]:
    """
    Compute exact algebraic closure ratio R_exact = Gamma_2 / Phi_1 for Phi_1 > 0.
    Returns Fraction(0, 1) if Phi_1 == 0 and Gamma_2 == 0.
    Returns None if Phi_1 == 0 and Gamma_2 > 0 (undefined / infinite).
    """
    if phi1 > Fraction(0, 1):
        return gamma2 / phi1
    if gamma2 == Fraction(0, 1):
        return Fraction(0, 1)
    return None


def compute_r_epsilon(
    phi1: Fraction,
    gamma2: Fraction,
    epsilon_guard: Fraction = Fraction(1, 1000),
) -> Tuple[Optional[Fraction], str]:
    """
    Compute piecewise closure ratio R_epsilon and named routing status (Section 3b):
    - If Phi_1 > epsilon_guard: R_epsilon = Gamma_2 / Phi_1, status = 'REGULAR'
    - If Phi_1 <= epsilon_guard and Gamma_2 <= epsilon_guard: R_epsilon = 0, status = 'SUB_EPSILON_FLAT'
    - If Phi_1 <= epsilon_guard and Gamma_2 > epsilon_guard: R_epsilon = None, status = 'UNBOUNDED_CURVATURE_SENTINEL'
    """
    if phi1 > epsilon_guard:
        return gamma2 / phi1, "REGULAR"
    if gamma2 <= epsilon_guard:
        return Fraction(0, 1), "SUB_EPSILON_FLAT"
    return None, "UNBOUNDED_CURVATURE_SENTINEL"


def compute_r_cl(
    phi1: Fraction,
    gamma2: Fraction,
    epsilon_guard: Fraction = Fraction(1, 1000),
) -> Optional[Fraction]:
    """Backward-compatible wrapper returning the piecewise R_epsilon value."""
    r_eps, _ = compute_r_epsilon(phi1, gamma2, epsilon_guard)
    return r_eps


def evaluate_tuple_acceptance(
    policy: EvaluatorPolicy,
    before_diag: ObstructionTuple,
    after_diag: Optional[ObstructionTuple],
) -> Tuple[bool, str]:
    """
    Pure diagnostic tuple predicate implementing the Guarded Descent Law (Section 6).
    Evaluates strict lexicographic descent on (Phi_1, Gamma_2, Xi) subject to the hard R_cl gate.
    Isolated from carrier and field binding for pure mathematical testing.
    """
    if after_diag is None:
        return False, "Rejected: Transition evaluation under Guarded Descent Law requires both before and after states."

    # Gate 0: R_cl guard on target state (hard piecewise guard)
    if after_diag.r_cl is None:
        return False, "Rejected: Closure ratio R_cl is +infinity (unbounded curvature: Gamma_2 > epsilon while Phi_1 <= epsilon)"
    if after_diag.r_cl > policy.max_r_cl:
        return False, f"Rejected: Closure ratio R_cl ({after_diag.r_cl}) exceeds policy ceiling ({policy.max_r_cl})"

    # Optional static ceiling checks on target state
    if policy.max_phi1 is not None and after_diag.phi1 > policy.max_phi1:
        return False, f"Rejected: Phi_1 ({after_diag.phi1}) exceeds policy ceiling ({policy.max_phi1})"
    if policy.max_gamma2 is not None and after_diag.gamma2 > policy.max_gamma2:
        return False, f"Rejected: Gamma_2 ({after_diag.gamma2}) exceeds policy ceiling ({policy.max_gamma2})"

    # Guarded Descent Law: strict lexicographic descent on (Phi_1, Gamma_2, Xi)
    # 1. Primary descent: Phi_1 strictly decreases
    if after_diag.phi1 < before_diag.phi1:
        return True, "Accepted: Strict decrease in Phi_1 (primary descent)."

    # 2. Second-order tiebreak: Phi_1 unchanged, Gamma_2 strictly decreases
    if after_diag.phi1 == before_diag.phi1:
        if after_diag.gamma2 < before_diag.gamma2:
            return True, "Accepted: Phi_1 unchanged, strict decrease in Gamma_2 (second-order tiebreak)."
        if after_diag.gamma2 == before_diag.gamma2:
            # 3. Third-order tiebreak: Phi_1 and Gamma_2 unchanged, Xi strictly decreases
            if after_diag.xi < before_diag.xi:
                return True, "Accepted: Phi_1 and Gamma_2 unchanged, strict decrease in Xi (third-order tiebreak)."
            if after_diag.xi == before_diag.xi:
                return False, "Rejected: Unchanged obstruction tuple (no strict descent)."
            return False, f"Rejected: Xi strictly increased from {before_diag.xi} to {after_diag.xi} under Phi_1 and Gamma_2 tie."
        return False, f"Rejected: Gamma_2 strictly increased from {before_diag.gamma2} to {after_diag.gamma2} under Phi_1 tie."

    return False, f"Rejected: Phi_1 strictly increased from {before_diag.phi1} to {after_diag.phi1} (worsening proposal)."


class GuardedEvaluator:
    """
    Guarded Evaluator implementing Evaluator Supremacy, Carrier Binding, and the Guarded Descent Law.
    Acceptance is strictly a function of evaluator-certified diagnostic transitions and declared policy;
    operator metadata is completely ignored.
    """
    def __init__(
        self,
        policy: EvaluatorPolicy,
        admitted_complex: Optional[AdmittedComplex] = None,
        xi_evaluator: Optional[Callable[[Tuple[Fraction, ...]], Fraction]] = None,
    ) -> None:
        self.policy = policy
        self.complex = admitted_complex
        self.xi_evaluator = xi_evaluator

    def evaluate_diagnostics(
        self,
        phi1: Fraction,
        gamma2: Fraction,
        xi: Fraction = Fraction(0, 1),
    ) -> ObstructionTuple:
        """Compute complete diagnostic tuple including exact ratio and routing status."""
        r_cl, routing_status = compute_r_epsilon(phi1, gamma2, self.policy.epsilon_guard)
        r_exact = compute_r_exact(phi1, gamma2)
        return ObstructionTuple(
            phi1=phi1,
            gamma2=gamma2,
            r_cl=r_cl,
            xi=xi,
            r_exact=r_exact,
            routing_status=routing_status,
        )

    def evaluate_field_diagnostics(
        self,
        field: Union[Tuple[Fraction, ...], List[Fraction]],
        d1_matrix: Optional[Union[List[List[int]], Tuple[Tuple[int, ...], ...]]] = None,
        complex_override: Optional[AdmittedComplex] = None,
        witness: Optional[ExactPrimalDualWitness] = None,
        xi: Optional[Fraction] = None,
    ) -> ObstructionTuple:
        """
        Independently compute diagnostics directly from a 1-cochain field:
        1. If a graph/complex is provided or admitted, uses exact primal/dual witness certification.
        2. Evaluates Gamma_2 only when a 2-cell matrix is declared; otherwise Gamma_2 is neutral 0.
        3. Evaluates Xi using bound xi_evaluator or declared neutral convention (0).
        """
        field_tuple = tuple(field)
        active_complex = complex_override or self.complex

        if active_complex is not None:
            if len(field_tuple) != len(active_complex.graph.edges):
                raise ValueError(
                    f"Field dimension ({len(field_tuple)}) does not match admitted complex edges ({len(active_complex.graph.edges)})"
                )
            if witness is not None:
                phi1 = verify_primal_dual_witness(active_complex.graph, field_tuple, witness)
            else:
                phi1, _ = solve_graph_l1_exact(active_complex.graph, field_tuple)
            active_d1 = d1_matrix if d1_matrix is not None else active_complex.d1_matrix
        else:
            active_d1 = d1_matrix
            phi1 = compute_phi1_cycle_graph(field_tuple)

        if active_d1 is not None:
            gamma2 = compute_gamma2_simple(active_d1, field_tuple)
        else:
            gamma2 = Fraction(0, 1)

        if self.xi_evaluator is not None:
            computed_xi = self.xi_evaluator(field_tuple)
        else:
            computed_xi = xi if xi is not None else Fraction(0, 1)

        return self.evaluate_diagnostics(phi1=phi1, gamma2=gamma2, xi=computed_xi)

    def evaluate_acceptance(
        self,
        proposal: OperatorProposal,
        before_diag: ObstructionTuple,
        after_diag: Optional[ObstructionTuple] = None,
        d1_matrix: Optional[Union[List[List[int]], Tuple[Tuple[int, ...], ...]]] = None,
        complex_override: Optional[AdmittedComplex] = None,
        before_witness: Optional[ExactPrimalDualWitness] = None,
        after_witness: Optional[ExactPrimalDualWitness] = None,
    ) -> Tuple[bool, str]:
        """
        Evaluate acceptance under the Guarded Descent Law (Section 6).
        Enforces:
        1. Carrier Dimension Integrity: ordinary proposals cannot change carrier dimension.
        2. Certified Field Binding: verifies that supplied diagnostics match the actual
           initial_field and proposed_field, gating only on evaluator-owned evidence.
        3. No-Complex Gamma Discipline: rejects caller-supplied Gamma values when no 2-complex exists.
        4. External-Xi Trust Boundary: rejects caller-supplied Xi descent on unchanged fields.
        5. Evaluator Supremacy: proposal.operator_id and proposal.parameters are unread.
        """
        if after_diag is None:
            return False, "Rejected: Transition evaluation under Guarded Descent Law requires both before and after states."

        active_complex = complex_override or self.complex

        # 1. Carrier Dimension Binding (R2)
        if active_complex is not None:
            expected_dim = len(active_complex.graph.edges)
            if len(proposal.initial_field) != expected_dim:
                return False, (
                    f"Rejected: initial_field dimension ({len(proposal.initial_field)}) does not match "
                    f"admitted carrier dimension ({expected_dim})."
                )
            if len(proposal.proposed_field) != expected_dim:
                return False, (
                    f"Rejected: proposed_field dimension ({len(proposal.proposed_field)}) does not match "
                    f"admitted carrier dimension ({expected_dim})."
                )
        else:
            if len(proposal.initial_field) != len(proposal.proposed_field):
                return False, (
                    f"Rejected: Ordinary proposal changes carrier dimension from "
                    f"{len(proposal.initial_field)} to {len(proposal.proposed_field)} without structural operator declaration."
                )

        # 2. Compute certified evaluator-owned diagnostics (R1, R2, R3, R5, R7)
        certified_before = self.evaluate_field_diagnostics(
            proposal.initial_field,
            d1_matrix=d1_matrix,
            complex_override=active_complex,
            witness=before_witness,
            xi=before_diag.xi,
        )
        certified_after = self.evaluate_field_diagnostics(
            proposal.proposed_field,
            d1_matrix=d1_matrix,
            complex_override=active_complex,
            witness=after_witness,
            xi=after_diag.xi,
        )

        # 3. Check for undeclared complex Gamma injection (R1)
        active_d1 = d1_matrix if d1_matrix is not None else (active_complex.d1_matrix if active_complex else None)
        if active_d1 is None:
            if before_diag.gamma2 != Fraction(0, 1):
                return False, "Rejected: No second differential declared; before_diag Gamma_2 must be neutral convention (0)."
            if after_diag.gamma2 != Fraction(0, 1):
                return False, "Rejected: No second differential declared; after_diag Gamma_2 must be neutral convention (0)."

        # 4. Field binding verification across all diagnostic fields (R1, R5)
        if before_diag.phi1 != certified_before.phi1:
            return False, (
                f"Rejected: Supplied before_diag Phi_1 ({before_diag.phi1}) does not match "
                f"certified initial_field Phi_1 ({certified_before.phi1})."
            )
        if before_diag.gamma2 != certified_before.gamma2:
            return False, (
                f"Rejected: Supplied before_diag Gamma_2 ({before_diag.gamma2}) does not match "
                f"certified initial_field Gamma_2 ({certified_before.gamma2})."
            )
        if before_diag.r_cl != certified_before.r_cl:
            return False, (
                f"Rejected: Supplied before_diag R_cl ({before_diag.r_cl}) does not match "
                f"certified initial_field R_cl ({certified_before.r_cl})."
            )

        if after_diag.phi1 != certified_after.phi1:
            return False, (
                f"Rejected: Supplied after_diag Phi_1 ({after_diag.phi1}) does not match "
                f"certified proposed_field Phi_1 ({certified_after.phi1})."
            )
        if after_diag.gamma2 != certified_after.gamma2:
            return False, (
                f"Rejected: Supplied after_diag Gamma_2 ({after_diag.gamma2}) does not match "
                f"certified proposed_field Gamma_2 ({certified_after.gamma2})."
            )
        if after_diag.r_cl != certified_after.r_cl:
            return False, (
                f"Rejected: Supplied after_diag R_cl ({after_diag.r_cl}) does not match "
                f"certified proposed_field R_cl ({certified_after.r_cl})."
            )

        # External-Xi trust boundary enforcement: prevent caller from manufacturing Xi descent on unchanged fields
        if self.xi_evaluator is None and proposal.initial_field == proposal.proposed_field:
            if before_diag.xi != after_diag.xi:
                return False, (
                    "Rejected: External Xi trust boundary: disparate caller-supplied Xi values "
                    "cannot create descent on an unchanged field without an evaluator-bound Xi verifier."
                )

        # 5. Evaluate strict lexicographic descent on certified tuples via pure predicate
        return evaluate_tuple_acceptance(self.policy, certified_before, certified_after)

    def evaluate_proposal_step(
        self,
        proposal: OperatorProposal,
        d1_matrix: Optional[Union[List[List[int]], Tuple[Tuple[int, ...], ...]]] = None,
        complex_override: Optional[AdmittedComplex] = None,
        before_witness: Optional[ExactPrimalDualWitness] = None,
        after_witness: Optional[ExactPrimalDualWitness] = None,
        before_xi: Fraction = Fraction(0, 1),
        after_xi: Fraction = Fraction(0, 1),
    ) -> Tuple[bool, str, ObstructionTuple, ObstructionTuple]:
        """
        Independently compute diagnostics directly from initial_field and proposed_field,
        then evaluate strict lexicographic descent under Evaluator Supremacy.
        """
        active_complex = complex_override or self.complex

        # Carrier dimension check
        if active_complex is not None:
            expected_dim = len(active_complex.graph.edges)
            if len(proposal.initial_field) != expected_dim:
                reason = f"Rejected: initial_field dimension ({len(proposal.initial_field)}) != carrier dimension ({expected_dim})"
                dummy = ObstructionTuple(Fraction(0), Fraction(0), Fraction(0))
                return False, reason, dummy, dummy
            if len(proposal.proposed_field) != expected_dim:
                reason = f"Rejected: proposed_field dimension ({len(proposal.proposed_field)}) != carrier dimension ({expected_dim})"
                dummy = ObstructionTuple(Fraction(0), Fraction(0), Fraction(0))
                return False, reason, dummy, dummy
        else:
            if len(proposal.initial_field) != len(proposal.proposed_field):
                reason = (
                    f"Rejected: Ordinary proposal changes carrier dimension from "
                    f"{len(proposal.initial_field)} to {len(proposal.proposed_field)} without structural operator declaration."
                )
                dummy = ObstructionTuple(Fraction(0), Fraction(0), Fraction(0))
                return False, reason, dummy, dummy

        before_diag = self.evaluate_field_diagnostics(
            proposal.initial_field,
            d1_matrix=d1_matrix,
            complex_override=active_complex,
            witness=before_witness,
            xi=before_xi,
        )
        after_diag = self.evaluate_field_diagnostics(
            proposal.proposed_field,
            d1_matrix=d1_matrix,
            complex_override=active_complex,
            witness=after_witness,
            xi=after_xi,
        )

        accepted, reason = self.evaluate_acceptance(
            proposal=proposal,
            before_diag=before_diag,
            after_diag=after_diag,
            d1_matrix=d1_matrix,
            complex_override=active_complex,
            before_witness=before_witness,
            after_witness=after_witness,
        )
        return accepted, reason, before_diag, after_diag

    def evaluate_structural_proposal_step(
        self,
        proposal: StructuralOperatorProposal,
    ) -> Tuple[bool, str, ObstructionTuple, ObstructionTuple]:
        """
        Evaluate candidate field transition generated by a structural operator across carriers.
        Requires explicit source and target AdmittedComplex carriers and carrier map.
        """
        src_dim = len(proposal.source_carrier.graph.edges)
        tgt_dim = len(proposal.target_carrier.graph.edges)
        if len(proposal.initial_field) != src_dim:
            reason = f"Rejected: initial_field dimension ({len(proposal.initial_field)}) != source carrier edges ({src_dim})"
            dummy = ObstructionTuple(Fraction(0), Fraction(0), Fraction(0))
            return False, reason, dummy, dummy
        if len(proposal.proposed_field) != tgt_dim:
            reason = f"Rejected: proposed_field dimension ({len(proposal.proposed_field)}) != target carrier edges ({tgt_dim})"
            dummy = ObstructionTuple(Fraction(0), Fraction(0), Fraction(0))
            return False, reason, dummy, dummy

        before_diag = self.evaluate_field_diagnostics(
            proposal.initial_field,
            complex_override=proposal.source_carrier,
        )
        after_diag = self.evaluate_field_diagnostics(
            proposal.proposed_field,
            complex_override=proposal.target_carrier,
        )
        accepted, reason = evaluate_tuple_acceptance(self.policy, before_diag, after_diag)
        return accepted, reason, before_diag, after_diag


def evaluate_path_acceptance(
    evaluator: GuardedEvaluator,
    proposals: List[OperatorProposal],
    complex: Optional[AdmittedComplex] = None,
) -> Tuple[bool, str, List[Tuple[ObstructionTuple, ObstructionTuple]]]:
    """
    Evaluate acceptance along a finite path of proposal steps.
    Requires:
    1. Every member proposal step is accepted by the guarded evaluator.
    2. Endpoint continuity: the proposed_field of step k must match the initial_field of step k+1.
    Evaluator Supremacy ensures path acceptance is invariant under operator metadata replacement.
    """
    if not proposals:
        return False, "Rejected: Path contains zero proposal steps.", []

    traces: List[Tuple[ObstructionTuple, ObstructionTuple]] = []
    for step_idx, step in enumerate(proposals):
        if step_idx > 0:
            prev_step = proposals[step_idx - 1]
            if step.initial_field != prev_step.proposed_field:
                return (
                    False,
                    f"Rejected: Path continuity broken at step {step_idx}: initial field does not match preceding target.",
                    traces,
                )
        accepted, reason, b_diag, a_diag = evaluator.evaluate_proposal_step(step, complex_override=complex)
        traces.append((b_diag, a_diag))
        if not accepted:
            return False, f"Rejected: Step {step_idx} failed: {reason}", traces

    return True, f"Accepted: All {len(proposals)} path steps certified under Guarded Descent Law.", traces
